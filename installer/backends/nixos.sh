# shellcheck shell=bash
# NixOS: declarative only. The installer never edits /etc/nixos. It writes a
# NixOS module with your choices to ~/.config/ssh-shell/nixos/ssh-shell.nix,
# shows exactly where it goes in your flake, and can run nixos-rebuild for
# you once you have added it.

be_label() { echo "Nix flake + NixOS module (declarative)"; }
be_names() {
    case $1 in
        core) echo "quickshell inter jetbrains-mono" ;;
        hyprland) echo "hyprland" ;;
        niri) echo "niri" ;;
        audio) echo "pipewire" ;;
        network) echo "networkmanager" ;;
        bluetooth) echo "bluez" ;;
        battery) echo "upower" ;;
        power) echo "power-profiles-daemon" ;;
        brightness) echo "brightnessctl" ;;
        notify) echo "libnotify" ;;
        term:*) echo "${1#term:}" ;;
        *) echo "" ;;
    esac
}
be_conflict() { :; }
be_pkg_installed() { have "$1" || [ -e "/run/current-system/sw/bin/$1" ]; }
be_pkg_available() { printf '%s\n' "$@"; }
be_extra_repos() { :; }
be_setup_repos() { :; }
be_ssh_installed() { have ssh-shell && ssh-shell version 2>/dev/null; }

nix_bool() { [ "$1" = 1 ] && echo true || echo false; }

# Writes the module; prints its path.
nixos_write_module() {
    local dir=${XDG_CONFIG_HOME:-$HOME/.config}/ssh-shell/nixos f
    f=$dir/ssh-shell.nix
    mkdir -p "$dir"
    [ -f "$f" ] && cp -f "$f" "$f.bak-$(date +%Y%m%d-%H%M%S)"
    {
        echo "# Generated by the SSH installer on $(date +%F). Add this file to your"
        echo "# system's modules together with ssh-shell.nixosModules.default."
        echo "{ pkgs, ... }: {"
        echo "  programs.ssh-shell = {"
        echo "    enable = true;"
        echo "    hyprland.enable = $(nix_bool "$WANT_HYPRLAND");"
        echo "    niri.enable = $(nix_bool "$WANT_NIRI");"
        echo "  };"
        [ -n "$TERMINAL_PKG" ] && echo "  environment.systemPackages = [ pkgs.$TERMINAL_PKG ];"
        echo ""
        echo "  # System integrations SSH reads when present. Uncomment what you want;"
        echo "  # they change system services, so they are left to you."
        [ "${INT[audio]}" = 1 ] && echo "  # services.pipewire = { enable = true; wireplumber.enable = true; };"
        [ "${INT[network]}" = 1 ] && echo "  # networking.networkmanager.enable = true;"
        [ "${INT[bluetooth]}" = 1 ] && echo "  # hardware.bluetooth.enable = true;"
        [ "${INT[power]}" = 1 ] && echo "  # services.power-profiles-daemon.enable = true;"
        echo "}"
    } >"$f"
    echo "$f"
}

nixos_flow() {
    local mod flake=/etc/nixos/flake.nix
    ui_step "Writing your NixOS module"
    mod=$(nixos_write_module)
    if have nix-instantiate && nix-instantiate --parse "$mod" >/dev/null 2>>"$UI_LOG"; then ui_ok "$mod (syntax checked)"
    else ui_ok "$mod"; fi
    ui_step "Add SSH to your system configuration"
    if [ -f "$flake" ]; then
        ui_note "Your system uses a flake ($flake). Add the input and two modules:"
        cat <<EOF

    inputs.ssh-shell.url = "github:ogjulius/SSH---Sovereignity-Shell";
    inputs.ssh-shell.inputs.nixpkgs.follows = "nixpkgs";

    # in outputs, for your host:
    nixosConfigurations.<host> = nixpkgs.lib.nixosSystem {
      modules = [
        ./configuration.nix
        ssh-shell.nixosModules.default
        $mod
      ];
    };

EOF
        ui_note "(Add 'ssh-shell' to the outputs function's arguments. To build from this"
        ui_note " checkout instead of GitHub, use: inputs.ssh-shell.url = \"path:$REPO\";)"
    else
        ui_note "No /etc/nixos/flake.nix: with flakes enabled, add to configuration.nix:"
        cat <<EOF

    imports = [
      (builtins.getFlake "github:ogjulius/SSH---Sovereignity-Shell").nixosModules.default
      $mod
    ];

EOF
        ui_note "(nix.settings.experimental-features = [ \"nix-command\" \"flakes\" ]; must be set.)"
    fi
    ui_note "The installer does not edit /etc/nixos for you."
    if ui_confirm "Have you added it, and should the installer run 'sudo nixos-rebuild switch' now?" n; then
        ui_run_fg "nixos-rebuild switch" $PRIV nixos-rebuild switch || { ui_err "nixos-rebuild failed; your previous generation is unchanged and still booted"; return 1; }
        NIXOS_REBUILT=1
    else
        ui_warn "Run 'sudo nixos-rebuild switch' after adding the module; then run ./install.sh again to validate."
        NIXOS_REBUILT=0
    fi
}
be_remove_hint() { echo "remove the ssh-shell lines from your NixOS configuration and run sudo nixos-rebuild switch"; }
