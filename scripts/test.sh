#!/usr/bin/env bash
# SSH test runner.
#   1. Unit tests for the pure-JS core (src/dev-tests.qml) in Quickshell's engine.
#   2. qmllint over every QML file (warnings shown, only hard errors fail).
#   3. A load test: the full shell starts offscreen-free on Wayland if available,
#      otherwise the render harness proves every surface instantiates.
set -uo pipefail
cd "$(dirname "$0")/.."
fail=0
strip() { sed 's/\x1b\[[0-9;]*m//g'; }

echo "── unit tests"
out=$(QT_QPA_PLATFORM=offscreen timeout 30 qs -p src/dev-tests.qml 2>&1 | strip)
echo "$out" | grep -E "FAIL|RESULT|got:|want:" | sed 's/^ *DEBUG qml: /  /'
if ! echo "$out" | grep -qE "RESULT [0-9]+ passed, 0 failed"; then fail=1; fi

echo "── qmllint (Qt 6)"
QMLLINT=""
for c in /usr/lib/qt6/bin/qmllint /usr/lib64/qt6/bin/qmllint qmllint6 qmllint; do
    if command -v "$c" >/dev/null 2>&1 && "$c" --version 2>/dev/null | grep -q "qmllint 6"; then QMLLINT=$c; break; fi
done
if [ -n "$QMLLINT" ]; then
    # qs.* modules are generated by Quickshell at runtime, so import/type
    # resolution warnings are expected; syntax errors are not.
    lint=$(find src -name '*.qml' -print0 | xargs -0 "$QMLLINT" 2>&1 | strip)
    syntax=$(echo "$lint" | grep -E "\[syntax\]$" || true)
    echo "  $(echo "$lint" | grep -c '^Warning') advisory warnings (unresolved runtime imports etc.)"
    if [ -n "$syntax" ]; then echo "$syntax"; fail=1; else echo "  no syntax errors"; fi
else
    echo "  Qt 6 qmllint not found, skipped"
fi

echo "── load test (all surfaces instantiate)"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
log=$(QT_QPA_PLATFORM=offscreen SSH_SHELL_NO_NOTIFICATIONS=1 SSH_SHELL_CONFIG="$tmp/none.json" \
      SSH_RENDER_OUT="$tmp" timeout 90 qs -p src/dev-render.qml 2>&1 | strip)
errs=$(echo "$log" | grep -E "ERROR|TypeError|ReferenceError|is not defined|Cannot read property" | grep -v "Tray.qml" || true)
n=$(ls "$tmp"/*.png 2>/dev/null | wc -l)
echo "  rendered $n surface(s)"
if [ -n "$errs" ]; then echo "$errs" | sort | uniq -c; fail=1; fi
[ "$n" -ge 8 ] || fail=1

if [ $fail -eq 0 ]; then echo "── all checks passed"; else echo "── FAILED"; fi
exit $fail
